import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { root } from './check-research.mjs';
import { schema } from '../packages/file-format/schema/v1.mjs';

export function schemaType(node) {
  if (node.$ref) return node.$ref.split('/').at(-1);
  if (node.oneOf) return `(${node.oneOf.map(schemaType).join(' | ')})`;
  if ('const' in node) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map(v => JSON.stringify(v)).join(' | ');
  if (node.type === 'object') return `{ ${Object.entries(node.properties).map(([key, value]) => `readonly ${JSON.stringify(key)}${node.required.includes(key) ? '' : '?'}: ${schemaType(value)}`).join('; ')} }`;
  if (node.type === 'array') return node.prefixItems ? `readonly [${node.prefixItems.map(schemaType).join(', ')}]` : `ReadonlyArray<${schemaType(node.items)}>`;
  const types = { string: 'string', number: 'number', integer: 'number', boolean: 'boolean', null: 'null' };
  if (!types[node.type]) throw new Error(`Unsupported schema type ${node.type}`);
  return types[node.type];
}
const outputs = [
  ['packages/file-format/schema/v1.schema.json', JSON.stringify(schema, null, 2) + '\n'],
  ['packages/document-model/src/dto.ts', '// Generated by scripts/generate-contracts.mjs from the explicit v1 schema. Do not edit.\n// Structural types do not replace numeric, reference, topology or resource validation.\n' +
    Object.entries(schema.$defs).map(([name, node]) => `export type ${name} = ${schemaType(node)};`).join('\n\n') + '\n'],
];
for (const [path, content] of outputs) {
  if (process.argv.includes('--check')) {
    let saved; try { saved = await readFile(resolve(root, path), 'utf8'); } catch { saved = ''; }
    if (saved.replaceAll('\r\n', '\n') !== content) { console.error(`Contract artifact out of date: ${path}`); process.exitCode = 1; }
  } else { await mkdir(resolve(root, path, '..'), { recursive: true }); await writeFile(resolve(root, path), content); }
}
